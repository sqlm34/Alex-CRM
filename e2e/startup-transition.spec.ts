import { test, expect } from '@playwright/test'

for (const width of [320, 390, 1280]) test(`splash switches the entire viewport at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 844 })
  await page.clock.install()
  await page.goto('/scripts/startup-splash.preview.html')
  await expect(page.locator('.startup-splash')).toBeVisible()
  await page.addStyleTag({ content: '#root { transform: translateY(-150px); }' })
  await page.clock.fastForward(4500)
  const overlay = page.locator('.startup-splash')
  await expect(overlay).toHaveCSS('opacity', '1')
  await expect(page.locator('.startup-app')).toHaveCSS('visibility', 'hidden')
  expect(await overlay.evaluate(el => el.parentElement === document.body)).toBe(true)
  const box = await overlay.boundingBox()
  expect(box).toMatchObject({ x: 0, y: 0, width, height: 844 })
  await page.screenshot({ path: `test-results/splash-before-${width}.png` })
  await page.clock.fastForward(600)
  await expect(overlay).toHaveCount(0)
  await expect(page.locator('.startup-app')).toHaveCSS('visibility', 'visible')
  await expect(page.locator('html')).not.toHaveClass(/android-startup/)
  await expect(page.getByLabel('Retained draft')).toHaveValue('Draft preserved')
  await page.addStyleTag({ content: '#root { transform: none; }' })
  await page.screenshot({ path: `test-results/splash-after-${width}.png` })
})
